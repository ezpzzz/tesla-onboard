import { NextResponse } from "next/server";
import { isOwnerAuthConfigured } from "@/lib/owner-auth";
import { ownerEmailOtpType } from "@/lib/owner-email-verification";
import { safeOwnerNextPath } from "@/lib/owner-auth-redirect";
import { createClient } from "@/lib/supabase/server";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

function loginErrorUrl(origin: string, next: string): URL {
  const login = new URL("/login", origin);
  login.searchParams.set("next", next);
  login.searchParams.set("error", "magic_link");
  return login;
}

/**
 * Exchanges either the PKCE code generated by Supabase's built-in email flow
 * or the token hash from EVhost's branded confirmation/magic-link templates.
 *
 * The templates render verification URLs as
 * `/auth/callback?token_hash=...&type=signup|magiclink`.
 * Completing the exchange server-side lets @supabase/ssr persist the session
 * cookies before the browser is redirected into the protected owner surface.
 */
export async function GET(request: Request) {
  const requestUrl = new URL(request.url);
  const next = safeOwnerNextPath(requestUrl.searchParams.get("next"));
  const code = requestUrl.searchParams.get("code");
  const tokenHash = requestUrl.searchParams.get("token_hash");
  const type = ownerEmailOtpType(requestUrl.searchParams.get("type"));

  if (!isOwnerAuthConfigured() || (!code && (!tokenHash || !type))) {
    return NextResponse.redirect(loginErrorUrl(requestUrl.origin, next));
  }

  try {
    const supabase = await createClient();
    const { error } = code
      ? await supabase.auth.exchangeCodeForSession(code)
      : await supabase.auth.verifyOtp({ token_hash: tokenHash!, type: type! });
    if (error) {
      return NextResponse.redirect(loginErrorUrl(requestUrl.origin, next));
    }
  } catch {
    return NextResponse.redirect(loginErrorUrl(requestUrl.origin, next));
  }

  return NextResponse.redirect(new URL(next, requestUrl.origin));
}
